export async function POST(req: NextRequest): Promise<Response> {
  try {
    const session = await requireSmWrite(...ADMIN_ROLES);
    const body = await req.json();
    const { runway } = body as {
      runway?: string;
    };

    if (!runway) {
      return NextResponse.json(
        { success: false, message: 'runway is required' },
        { status: 400 },
      );
    }

    const runways = await listRunways();
    const rw = runways.find((r) => r.name === runway || r.slug === runway);
    if (!rw) {
      return NextResponse.json(
        { success: false, message: `Unknown runway: ${runway}` },
        { status: 400 },
      );
    }

    const stats = await getAggregatedStats(session, rw.slug);

    // Read stored recipients
    const recipientData = await readTeamFile(
      'restart-monitor-recipients.json',
      MonthlyRecipients,
    );
    const toAddresses = recipientData.recipients.map((r) => r.email);

    // Send email if there are recipients
    let emailSent = false;
    let emailError: string | null = null;
    if (toAddresses.length > 0) {
      const now = new Date();
      const monthLabel = now.toLocaleDateString('en-US', {
        year: 'numeric',
        month: 'long',
      });
      const html = buildMonthlyEmailHtml(rw.name, stats);
      const result = await sendMail({
        to: toAddresses,
        subject: `[SOM] Restart Monitor Monthly Report - ${rw.name} - ${monthLabel}`,
        html,
        team: session.team,
        sent_by: session.sub,
        sent_by_name: session.username,
        log_type: 'restart_monitor_monthly',
      });
      emailSent = result.ok;
      emailError = result.error;
    }

    await logActivity({
      user: session.sub,
      team: session.team,
      action: 'restart_monitor_monthly_send',
      meta: {
        runway: rw.name,
        recipientCount: toAddresses.length,
        emailSent,
        emailError,
        triggeredBy: session.username,
      },
    });

    return NextResponse.json({
      success: true,
      data: {
        message: emailSent
          ? 'Monthly report sent'
          : toAddresses.length === 0
            ? 'No recipients configured'
            : `Email failed: ${emailError}`,
        runway: rw.name,
        stats,
        recipientCount: toAddresses.length,
        emailSent,
      },
    });
  } catch (e) {
    const status = (e as { status?: number }).status ?? 500;
    return NextResponse.json(
      { success: false, message: (e as Error).message },
      { status },
    );
  }
}
